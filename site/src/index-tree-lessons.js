function pages(root, leaves, caption, options = {}) {
  const positions = leaves.length ? [['root', 50, 25], ['left', 25, 72], ['right', 75, 72]] : [['root', 50, 48]]
  return {
    type: 'graph', kind: 'pages', nodes: positions, edges: leaves.length ? [['root', 'left'], ['root', 'right']] : [],
    labels: { root, left: leaves[0], right: leaves[1] }, caption, visited: [], ...options,
  }
}

